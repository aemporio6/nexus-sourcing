"""Builds src/app/starter.js — the standard lists a brand-new (empty) workspace starts with.
Taken from the working setup's GENERIC lists only: no company, bank, people, email, user, brand, alias or memory data."""
import json, sys
src = json.load(open(sys.argv[1]))["data"]["setup"]["main"]
KEEP_LISTS = [k for k in src["lists"] if k not in ("brand", "category", "legacyMap")]
lists = {k: src["lists"][k] for k in KEEP_LISTS}
lists["brand"] = {"label": src["lists"]["brand"].get("label", "Brands"), "group": src["lists"]["brand"].get("group", "Products"), "items": []}
cats = [("HOME","Home & kitchen","HOM"),("BATH","Bathroom","BTH"),("CLEAN","Cleaning","CLN"),("PET","Pet supplies","PET"),("BEAUTY","Beauty & personal care","BTY"),
        ("HEALTH","Health","HLT"),("BABY","Baby","BBY"),("TOYS","Toys & games","TOY"),("GARDEN","Garden & outdoor","GRD"),("SPORT","Sports & fitness","SPT"),
        ("FASH","Clothing & accessories","FSH"),("ELEC","Electronics accessories","ELC"),("OFFICE","Office & stationery","OFC"),("CAR","Car accessories","CAR"),
        ("PACK","Packaging","PKG"),("OTHER","Other","OTH")]
lists["category"] = {**{k: v for k, v in src["lists"]["category"].items() if k != "items"}, "items": [{"id": i, "label": l, "code": c} for i, l, c in cats]}
lists["legacyMap"] = {**src["lists"].get("legacyMap", {"label": "Legacy value map"}), "items": []}
starter = {
  "lists": lists,
  "numbering": src.get("numbering", {}), "refPatterns": src.get("refPatterns", {}),
  "defaults": {k: v for k, v in src.get("defaults", {}).items() if k not in ("company", "receiveLoc", "sellLoc", "shipTo")},
  "fees": src.get("fees", {}), "roles": src.get("roles", {}),
  "companies": [{"id": "c1", "name": "My company", "tag": "CO", "default": True, "vatRegistered": False}],
  "locations": [{"id": "L1", "name": "Main store", "kind": "own", "default": {"receive": True, "sell": True}},
                {"id": "L2", "name": "Amazon FBA", "kind": "amazon"}],
}
rates = src.get("rates", {})
starter["rates"] = {"history": [{k: v for k, v in r.items() if k in ("date","RMB","USD","EUR","CAD","HKD")} | {"note": "starter rate — updated by itself daily"} for r in rates.get("history", []) if not r.get("auto")]}
for f in [k for k in src if k.startswith("fix2026")] + ["viewsSeeded", "v4defaults"]:
    starter[f] = True
out = "/* ---------- Starter kit for a brand-new workspace (generated by tools/gen/make_starter.py) ----------\n   Standard lists only — statuses, units, currencies, incoterms, payment types, ports, categories … — so no dropdown is ever empty.\n   No company, bank, people, user, brand or supplier data is in here. */\nconst STARTER_SETUP=" + json.dumps(starter, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(sys.argv[2], "w").write(out)
print("lists", len(lists), "bytes", len(out))
